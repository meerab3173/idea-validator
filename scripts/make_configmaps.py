"""Regenerate k8s/11-configmaps.generated.yaml from config/ and rubrics/.
Run after changing weights, thresholds, budgets or rubrics, then commit both."""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
NS = "idea-validator"


def cm(name, files):
    return {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": name, "namespace": NS},
            "data": {p.name: p.read_text() for p in files}}


docs = [
    cm("verdict-config", [ROOT / "config/verdict.yaml"]),
    cm("budgets-config", [ROOT / "config/budgets.yaml"]),
    cm("rubrics", sorted((ROOT / "rubrics").glob("*.yaml"))),
]
out = ROOT / "k8s/11-configmaps.generated.yaml"
out.write_text("# GENERATED by scripts/make_configmaps.py — do not edit by hand.\n" +
               yaml.safe_dump_all(docs, sort_keys=False, width=200))
print("wrote", out)
